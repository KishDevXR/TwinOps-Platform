"""
Generate web/src/constants/pilotAssets.ts (the viewer's offline snapshot) from the pilot
register, so frontend and backend cannot drift.

  python -m simulator.export_web > web/src/constants/pilotAssets.ts
"""

import json
import random
import sys

from services.common.twin_templates import TEMPLATES
from simulator.plant import VirtualPlant

random.seed(0)  # stable output
plant = VirtualPlant()
for _ in range(30):  # 30 s in: CNCs are mid-cut, forklift is carrying its first pallet
    messages = {m.asset_id: m for m in plant.tick(1.0)}

assets = {}
for aid, machine in plant.machines.items():
    cfg, msg = machine.config, messages[aid]
    units = {m.name: m.unit for m in TEMPLATES[cfg.type_id].metrics}
    assets[aid] = {
        "asset_id": aid,
        "name": cfg.name,
        "type_id": cfg.type_id,
        "status": msg.status.value,
        "status_color": "green" if msg.status.value == "RUNNING" else "amber",
        "line_id": cfg.line_id,
        "criticality": cfg.criticality,
        "position": cfg.position_3d,
        "metrics": {
            k: {"v": v.v, "q": int(v.q), "unit": units.get(k, "")} for k, v in msg.metrics.items()
        },
        "derived": {},
        "last_seen": "__NOW__",
        "is_stale": False,
        "anomaly_score": 0.05,
    }

body = json.dumps(assets, indent=2, ensure_ascii=False).replace('"__NOW__"', "NOW")
sys.stdout.reconfigure(encoding="utf-8", newline="\n")
print("// GENERATED by `python -m simulator.export_web` from simulator/config.py. Do not edit.")
print("import type { LiveAssetTwin } from '../types/twin'\n")
print("const NOW = new Date().toISOString()\n")
print(f"export const PILOT_ASSETS_INITIAL: Record<string, LiveAssetTwin> = {body}")
